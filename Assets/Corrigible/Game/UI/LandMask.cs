        /// <summary>1000×480 harita düzleminde kara üzerine düşen nokta merkezleri (altıgen ızgara).</summary>
        public static IReadOnlyList<Vector2> Dots => dots ??= Build();

        static Vector2 Proj(double lon, double lat) => new Vector2((float)((lon + 180) / 360 * 1000), (float)((78 - lat) / 136 * 480));

        static List<Vector2> Build()
        {
            var polys = new List<Vector2[]>();
            foreach (var flat in Polygons)
            {
                var pts = new Vector2[flat.Length / 2];
                for (int i = 0; i < pts.Length; i++) pts[i] = Proj(flat[2 * i], flat[2 * i + 1]);
                polys.Add(pts);
            }
            var result = new List<Vector2>();
            int row = 0;
            for (float y = 4.5f; y < 480; y += 8, row++)
                for (float x = 4.5f + (row % 2) * 4.5f; x < 1000; x += 9)
                    foreach (var poly in polys)
                        if (Inside(x, y, poly)) { result.Add(new Vector2(x, y)); break; }
            return result;
        }

        static bool Inside(float x, float y, Vector2[] poly)
        {
            bool c = false;
            for (int i = 0, j = poly.Length - 1; i < poly.Length; j = i++)
            {
                var pi = poly[i]; var pj = poly[j];
                if ((pi.y > y) != (pj.y > y) && x < (pj.x - pi.x) * (y - pi.y) / (pj.y - pi.y) + pi.x) c = !c;
            }
            return c;
        }
